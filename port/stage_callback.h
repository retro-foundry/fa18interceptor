#ifndef FA18_STAGE_CALLBACK_H
#define FA18_STAGE_CALLBACK_H

/* Semantic identities of native game stages. These are enum values, never
 * executable addresses. Each body must be supplied by its actual owner. */
typedef enum {
    FA18_STAGE_C0F920,
    FA18_STAGE_C0F946,
    FA18_STAGE_C1104C,
    FA18_STAGE_C11078,
    FA18_STAGE_EXISTING,
    FA18_STAGE_C0FA04,
    FA18_STAGE_C0FA4C,
    FA18_STAGE_C0FA80,
    FA18_STAGE_C10C08,
    FA18_STAGE_C0F812,
    FA18_STAGE_C11446,
    FA18_STAGE_C113E4
} FA18StageCallback;

/* Preserve existing native interfaces while giving both controllers the
 * same type; their old headers declared incompatible types with this name. */
typedef FA18StageCallback FA18PostInputCallback;
#define FA18_POST_INPUT_CALLBACK_C0F920 FA18_STAGE_C0F920
#define FA18_POST_INPUT_CALLBACK_C0F946 FA18_STAGE_C0F946
#define FA18_POST_INPUT_CALLBACK_C1104C FA18_STAGE_C1104C
#define FA18_POST_INPUT_CALLBACK_C11078 FA18_STAGE_C11078
#define FA18_POST_INPUT_CALLBACK_EXISTING FA18_STAGE_EXISTING
#define FA18_POST_INPUT_CALLBACK_FINISH_FOLLOWUP FA18_STAGE_C0FA04
#define FA18_POST_INPUT_CALLBACK_AFTER_FINISH_FOLLOWUP FA18_STAGE_C0FA4C
#define FA18_POST_INPUT_CALLBACK_COMPLETE_FOLLOWUP FA18_STAGE_C0FA80
#define FA18_POST_INPUT_CALLBACK_CONTINUE_AFTER_COMPLETE_FOLLOWUP FA18_STAGE_C10C08

#endif
